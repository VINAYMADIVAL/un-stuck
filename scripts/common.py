"""Shared helpers for the Unstuck fleet scripts. Standard library only."""
from __future__ import annotations

import hashlib
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AGENTS_DIR = ROOT / "agents"
CENTRAL_DIR = ROOT / "central"
BASE_BEGIN = "<!-- BASE:BEGIN -->"
BASE_END = "<!-- BASE:END -->"
CENTRAL_KEY = "central"
DEFAULT_CENTRAL_PROFILE = "unstuck-central"

MEMORY_WARN_BYTES = 20 * 1024  # a memory file this big is probably bloated


def load_local_config() -> dict:
    """Optional fleet.local.json (git-ignored) lets you map to profile names you already created."""
    p = ROOT / "fleet.local.json"
    if p.exists():
        return json.loads(p.read_text(encoding="utf-8"))
    return {}


def profiles_dir() -> Path:
    """Where Hermes keeps profiles. Order: $HERMES_PROFILES_DIR, fleet.local.json, %LOCALAPPDATA%\\hermes\\profiles
    (Windows), ~/.hermes/profiles (Linux/macOS)."""
    env = os.environ.get("HERMES_PROFILES_DIR")
    if env:
        return Path(env).expanduser()
    cfg = load_local_config().get("profiles_dir")
    if cfg:
        return Path(cfg).expanduser()
    local = os.environ.get("LOCALAPPDATA")
    if local and (Path(local) / "hermes" / "profiles").exists():
        return Path(local) / "hermes" / "profiles"
    return Path.home() / ".hermes" / "profiles"


def agent_dirs() -> list[Path]:
    return sorted(p for p in AGENTS_DIR.iterdir() if p.is_dir() and not p.name.startswith("_"))


def load_agent(agent_dir: Path) -> dict:
    meta = json.loads((agent_dir / "agent.json").read_text(encoding="utf-8"))
    meta["key"] = agent_dir.name
    override = load_local_config().get("profiles", {}).get(agent_dir.name)
    if override:
        meta["profile"] = override
    return meta


def central_profile_name() -> str:
    return load_local_config().get("profiles", {}).get(CENTRAL_KEY, DEFAULT_CENTRAL_PROFILE)


def extract_base(text: str) -> str | None:
    """Return the text between the BASE markers (markers excluded), or None."""
    if BASE_BEGIN not in text or BASE_END not in text:
        return None
    return text.split(BASE_BEGIN, 1)[1].split(BASE_END, 1)[0].strip()


def sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


def parse_frontmatter(text: str) -> dict:
    """Tiny YAML-subset parser: `key: value` lines between leading --- fences."""
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n", text, re.S)
    if not m:
        return {}
    out = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith((" ", "#")):
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip()
    return out


def compose_subagent_soul(central_soul: str, persona: str, platform: str) -> str:
    base = extract_base(central_soul)
    if base is None:
        raise ValueError("central/SOUL.md is missing BASE markers")
    return (
        f"<!-- GENERATED by scripts/install.py for agent '{platform}'. Do not edit the BASE block;"
        f" edit central/SOUL.md and re-run `make install`. -->\n"
        f"{BASE_BEGIN}\n{base}\n{BASE_END}\n\n{persona.strip()}\n"
    )
